#!/usr/bin/env python3
"""verdict.py: write VERDICT-SP1A.md from the evidence envelopes of this spike (never from memory, never from the stand-in CLIs).

USAGE  python3 -I spikes/sp1_craft_cli/drivers/verdict.py [--out FILE] [--print]
It reads release_assets.json, build/evidence/wp07/{t1,t2,t4}_<app>_<tag>.json (envelopes whose name ends in _mini are mechanism tests against a
stand-in CLI and are ignored here), stage_<id>.json, blocked_proof.json and download_ledger.jsonl. A test with no real envelope is written as
NOT RUN with the reason found in the stage envelope (for example the exact disk-guard refusal). T3 is WP-10's, T5 and T6 are not run (stated
in the file). The R8 decision rule is applied only to what was measured.
EXIT CODE  always 0 (it reports, it does not judge).
"""
import argparse
import glob
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sp1_lib as L  # noqa: E402

RULE = ("R8 decision rule (research/craft-motion.md): if T2 and T4 pass, agents may render drafts and chapters with the Craft CLIs in the container (still producing OTIO "
        "and ffmpeg fallbacks); if T2 fails, FilmCraft stays maker-side and the container renders with ffmpeg and code; if T4 fails on memory or speed, EffectCraft is limited to "
        "titles and line-draw on the maker's PC.")


def load(pattern):
    out = []
    for p in sorted(glob.glob(os.path.join(L.EVID, pattern))):
        if p.endswith("_mini.json"):
            continue
        try:
            d = L.read_json(p)
        except (OSError, ValueError):
            continue
        if isinstance(d, dict) and not d.get("detail", {}).get("mini"):
            out.append(d)
    return out


def mark_text(mark):
    """The mark column exactly as the envelope records it; only a pipe is changed, so that it cannot split a table cell. The 20 Oct 0.8.0 envelope (not re-run) records the h264_speed mark
    as "scaled from 3,000 frames" at the plan's old frame rate; the driver now words the same fact as "scaled to 2,400 frames at this film's 24 fps from R8's 3,000-frame figure".
    The older wording is history and is shown as recorded (w2t-t2-wording, d): the stale check allows it in this file by the entry AL-7 in scripts/stale_allowlist.json, which is scoped to
    VERDICT-SP1A.md and to that one phrase. Before that entry this function reworded the phrase at display time, so the verdict differed from its evidence by one phrase."""
    return str(mark).replace("|", "/")


def cell(env, what):
    if not env:
        return None
    return env


def result_word(envs):
    """PASS / FAIL / INCONCLUSIVE from a list of envelopes of one test (newest wins)."""
    if not envs:
        return None
    e = envs[-1]
    if e["status"] == "PASS":
        return "PASS"
    if e["status"] == "FAIL":
        return "FAIL"
    if (e.get("detail") or {}).get("harness_error"):
        return "INCONCLUSIVE (the driver could not drive the CLI)"
    if (e.get("detail") or {}).get("partial"):
        return "INCOMPLETE (the stage ended before this test finished; the criteria measured so far are in section 3)"
    return e["status"]


def stage_envelopes():
    """The real stage envelopes: the ones written by the deliberate wrong-asset test (detail.forced_bad_asset) are skipped, as build() skips a forced blocked_proof.json."""
    out = []
    for p in sorted(glob.glob(os.path.join(L.EVID, "stage_*.json"))):
        try:
            d = L.read_json(p)
        except (OSError, ValueError):
            continue
        if isinstance(d, dict) and not (d.get("detail") or {}).get("forced_bad_asset"):
            out.append((p, d))
    return out


def stage_reason(app=None):
    reasons = []
    for p, d in stage_envelopes():
        if app and ("stage_" + app) not in os.path.basename(p):
            continue
        if d["status"] in ("BLOCKED", "FAIL") or (d.get("detail") or {}).get("exit_code") not in (0, None):
            reasons.append("%s: %s (%s)" % (d["test"], d["status"], d["actual"]))
    return reasons


def build():
    assets = L.load_assets() if os.path.exists(L.ASSETS_FILE) else None
    t1 = {"filmcraft": load("t1_filmcraft_*.json"), "effectcraft": load("t1_effectcraft_*.json")}
    t2 = load("t2_filmcraft_*.json")
    t4 = load("t4_effectcraft_*.json")
    blocked = None
    bp = os.path.join(L.EVID, "blocked_proof.json")
    if os.path.exists(bp):
        blocked = L.read_json(bp)
        if (blocked.get("context") or {}).get("forced_bad_asset"):
            blocked = None  # written by the deliberate wrong-asset test: not a real block
    reasons = stage_reason()
    ledger_p = os.path.join(L.EVID, "download_ledger.jsonl")
    ledger = [json.loads(x) for x in open(ledger_p) if x.strip()] if os.path.exists(ledger_p) else []
    lines = []
    A = lines.append
    A("# SP1a verdict: the Craft command-line programs in the container (WP-07)")
    A("")
    A("*Generated by `spikes/sp1_craft_cli/drivers/verdict.py` from the evidence files in `build/evidence/wp07/` on %s. Nothing here is written by hand; a row says NOT RUN until a real run has produced an envelope. Stand-in CLIs used to test the harness are ignored.*" % L.today())
    A("")
    A("**A Linux CLI result proves nothing about Windows.** The maker's Sat 24 Oct five-minute tests (`MAKER-CRAFT-ZIPS.md`) are the Windows evidence. Everything below is about whether agents can use the CLIs in the cloud container, CPU only, no GPU.")
    A("")
    A("## 1. The test table")
    A("")
    A("| Test | What it checks | Result | Evidence |")
    A("|---|---|---|---|")

    def row(tid, what, envs, why_not, evid):
        w = result_word(envs)
        if w is None:
            w = "NOT RUN: " + why_not
        A("| %s | %s | %s | %s |" % (tid, what, w.replace("|", "/"), evid))

    def why_for(app):
        rs = stage_reason(app)
        if rs:
            return rs[0].replace("|", "/")
        if blocked:
            return "download blocked: HTTP %s, curl exit %s (see blocked_proof.json)" % (blocked["http_status"], blocked["curl_exit_code"])
        return "no stage has produced a result yet"

    row("T1 FilmCraft", "`--version`, command list, state query, describe, clean stderr, libraries", t1["filmcraft"], why_for("filmcraft"), "`t1_filmcraft_*.json`")
    row("T1 EffectCraft", "the same for `effectcraft-cli`", t1["effectcraft"], why_for("effectcraft"), "`t1_effectcraft_*.json`")
    row("T2 FilmCraft stills", "N = 5, 20, 100 at 3600x2400 and 300 at 2880x1620: no crash, RSS slope under 40 MB per still, RSS(300) under 12 GB; 2,400-frame H.264 at 5 fps or more; ProRes frame count; Ken Burns within 1 px; mid-dissolve within 2 levels of the linear-light mix of its neighbours (mark amended 20 Oct 2026); at least 11 distinct levels over a 12-frame exported dissolve (criterion added 20 Oct 2026); offlineMedia empty", t2, why_for("filmcraft"), "`t2_filmcraft_*.json`")
    A("| T3 interchange | OTIO, FCP7 XML, FCPXML, EDL import and export | done in WP-10 (from the FilmCraft tarball kept in `vendor/craft/_keep/` when the keep rule allowed) | WP-10 |")
    row("T4 EffectCraft", "title, line-draw and parallax at 1080p24 with `RAYON_NUM_THREADS=1`: no OOM, PNG alpha, parallax under 3 s/frame and 6 GB, ProRes 4444 and H.264 decode, determinism", t4, why_for("effectcraft"), "`t4_effectcraft_*.json`")
    A("| T5 SoundCraft | bounce and loudness | not run: SoundCraft is unpinned and learning-only (D-12); no decision depends on it | none |")
    A("| T6 web builds | the web zips in headless Chromium | not run: the web zips are not pins | none |")
    A("")
    A("## 2. The decision (R8 rule)")
    A("")
    A(RULE)
    A("")
    fc = result_word(t2)
    ec = result_word(t4)
    fc_t1 = result_word(t1["filmcraft"])
    if fc == "PASS" and ec == "PASS" and fc_t1 == "PASS":
        A("**Outcome: agents may render drafts and chapters with the Craft CLIs in the container (in this plan: drafts; `ROADMAP.md` row 136 keeps the FilmCraft chapter pass on the PC).** T2 and T4 passed on Linux CPU. Every chapter still keeps its OTIO and ffmpeg fallback (D-11, D-12), and nothing here says the apps run on the maker's PC.")
        if t2 and any(c["id"] == "T2.dissolve_steps" for c in (t2[-1].get("detail") or {}).get("criteria", [])):
            A("")
            A("**This T2 pass rests on the mark as amended on Tue 20 Oct 2026** (week-2 gate, nudge 1): the first run of the same pin (01:20 UTC) failed `T2.mid_dissolve` by 28.50 levels, because the "
              "first wording compared the frame with the average of the ENCODED values, which no gamma-correct compositor can pass; the mark became the 50/50 mix in linear light (same 2-level tolerance), "
              "`T2.dissolve_steps` was added, and the one 0.9.0 stage was re-run. The first run's envelopes are kept in `build/evidence/wp07/first-mark/`. The fallback 0.8.0 was not re-run (it is fetched "
              "only when the pin fails). **Practical rule: one chapter, one dissolve route.** FilmCraft blends in linear light; ffmpeg `xfade` and headless Chromium blend the encoded values, so the same "
              "dissolve has a different mid-tone on each (`build/evidence/wp07/dissolve_routes.json`, from `drivers/dissolve_routes.py`).")
    elif fc is None and ec is None:
        A("**Outcome: UNDECIDED. T2 and T4 have not been run.** Until they are, the plan's default stands: the container renders with ffmpeg, Pillow and Chromium (Route A), and FilmCraft and EffectCraft are maker-side refinement tools. ROADMAP 5.2 says \"Craft CLIs: only if SP1 T2/T4 pass\", so nothing is planned on them.")
        if reasons:
            A("")
            A("Why they have not run (the stage envelopes, copied):")
            for r in reasons:
                A("- " + r)
    else:
        parts = []
        parts.append("FilmCraft: " + ("T2 passed, so draft renders with `filmcraft-cli` are allowed in the container" if fc == "PASS" else "T2 is %s, so FilmCraft stays maker-side and the container renders with ffmpeg and code" % (fc or "NOT RUN")))
        parts.append("EffectCraft: " + ("T4 passed, so titles, line-draw and parallax drafts are allowed in the container" if ec == "PASS" else "T4 is %s, so EffectCraft is limited to titles and line-draw on the maker's PC" % (ec or "NOT RUN")))
        A("**Outcome (per app):** " + "; ".join(parts) + ".")
    A("")
    A("## 3. Measurements")
    A("")
    for env in t2 + t4:
        d = env.get("detail") or {}
        A("### %s (%s profile, %s)" % (env["test"], d.get("profile", "?"), env["date_utc"]))
        A("")
        A("| Criterion | Measured | Mark | Result |")
        A("|---|---|---|---|")
        for c in d.get("criteria", []):
            A("| `%s` | %s | %s | %s |" % (c["id"], str(c["measured"]).replace("|", "/"), mark_text(c["mark"]), "PASS" if c["pass"] else "FAIL"))
        A("")
        A("Timing validity: contaminated = %s (a run with another job's load visible is marked contaminated)." % d.get("contaminated", "?"))
        if env["test"].startswith("t2_") and not any(c["id"] == "T2.dissolve_steps" for c in d.get("criteria", [])) and any(
                any(c["id"] == "T2.dissolve_steps" for c in (e.get("detail") or {}).get("criteria", [])) for e in t2):
            A("")
            A("**Mark note:** this run is from before the T2 mark amendment of Tue 20 Oct 2026 (week-2 gate, nudge 1). Its `T2.mid_dissolve` compared the frame with the average of the "
              "ENCODED values, which no gamma-correct compositor can pass, and it had no `T2.dissolve_steps` criterion. It was not re-run (the fallback is fetched only when the pin fails); "
              "read it for the other criteria, and take the dissolve result from the run that has `T2.dissolve_steps`.")
        if d.get("partial"):
            A("")
            A("**Partial result:** %s" % env["actual"])
        if d.get("harness_error"):
            A("")
            A("Harness error (a command-surface surprise, not a verdict on the app): %s" % d["harness_error"])
        A("")
    A("## 4. Sums, hashes and the download ledger")
    A("")
    if assets:
        rc = assets["r8_comparison"]
        A("- `release_assets.json` (fetched %s): usable = %s; independent (R8) hash comparison: **%s** over %d values; sizes against the plan's HEAD figures: **%s**." % (assets["fetched_date_utc"], assets["usable"], rc["status"], len(rc["rows"]), assets["size_comparison"]["status"]))
        A("- PhotoCraft, VectorCraft and LightCraft have no independent value; their hashes prove integrity only. SoundCraft: %s." % assets["soundcraft"]["status"])
    A("- Download ledger: %d tarball fetches recorded%s." % (len(ledger), "".join("; %s (%s, %.1f MB)" % (r["asset"], r["stage"], r["bytes"] / 1048576.0) for r in ledger)))
    A("")
    A("## 5. Disk")
    A("")
    for p, d in stage_envelopes():
        dk = d["disk"]
        A("- `%s`: %s; Avail start %s MB, minimum %s MB, end %s MB; planned %s MB; profile %s." % (d["test"], d["status"], dk["avail_mb_start"], dk["avail_mb_min"], dk["avail_mb_end"], dk["planned_write_mb"], (d.get("detail") or {}).get("profile")))
    if not stage_envelopes():
        A("- No stage has run.")
    A("")
    A("## 6. What this does not say")
    A("")
    A("- Nothing about Windows, the apps' windows, graphics drivers or the maker's PC.")
    A("- Nothing about PhotoCraft, VectorCraft or LightCraft (WP-10) or SoundCraft (not run).")
    A("- Timings are CPU-only on a shared 4-vCPU container.")
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=os.path.join(L.SP1, "VERDICT-SP1A.md"))
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args(argv)
    text = L.scrub(build())
    if a.print:
        print(text)
    else:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote " + L.rel(a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
