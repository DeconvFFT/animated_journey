#!/usr/bin/env python3
"""assemble.py: builds spikes/VERDICTS-W2.md from one file per spike, so that no two writers ever share a verdict file (gate w2, nudge 6).

USAGE  python3 -I spikes/verdicts/assemble.py                 write spikes/VERDICTS-W2.md from template.md and SP1.md ... SP5.md (atomic; the same inputs always give the same bytes)
       python3 -I spikes/verdicts/assemble.py check           exit 0 if VERDICTS-W2.md is exactly what the parts assemble to, exit 1 if it is not (a forgotten assemble, or a hand edit of the generated file)
       python3 -I spikes/verdicts/assemble.py import          the reverse, for a one-time migration or to recover a hand edit: split the current VERDICTS-W2.md into template.md and the SPn.md parts
       options: --verdicts FILE (default spikes/VERDICTS-W2.md)  --dir DIR (default spikes/verdicts)      (both are for the tests)
THE RULE  See spikes/verdicts/README.md. In one line: each spike's row, rule line, test rows and "does not say" bullet live in that spike's own file, written only by the package that runs the
          spike; the prose around them lives in template.md, written only by the orchestrator; VERDICTS-W2.md is generated and nobody edits it by hand.
PART FILES  A part file holds sections introduced by a line `<!-- part: NAME -->`, NAME one of: row (one table row `| **SPn** | ... |`), rule (bullets `* SPn, ...`), tests (rows `| **Tn** ... |`, SP1 only),
          not-said (bullets for the "What this file does not say" section). Other `<!-- ... -->` comment lines are ignored (the owner note at the top).
TEMPLATE    template.md is VERDICTS-W2.md with four placeholder lines: `<!-- insert: rows -->`, `<!-- insert: rules -->`, `<!-- insert: tests -->`, `<!-- insert: not-said -->`.
EXIT CODES  0 done / in step   1 check found a difference   2 bad usage, unreadable file or a malformed part
Standard library only. Prints no path of the machine.
"""
import argparse
import difflib
import os
import re
import sys
import tempfile

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.realpath(os.path.join(HERE, "..", ".."))
BANNER = "<!-- GENERATED by spikes/verdicts/assemble.py from spikes/verdicts/template.md and SP1.md to SP5.md. Do not edit this file by hand: edit your spike's own file and run `python3 -I spikes/verdicts/assemble.py` (spikes/verdicts/README.md). -->"
SPIKES = ["SP1", "SP2", "SP3", "SP4", "SP5"]
PARTS = ["row", "rule", "tests", "not-said"]
INSERT = {"row": "rows", "rule": "rules", "tests": "tests", "not-said": "not-said"}
OWNER_NOTE = {
    "SP1": "the package that runs SP1 (the Craft CLI tests, WP-07 and WP-10 in the build plan)",
    "SP2": "the package that runs SP2 (Route A, WP-04)",
    "SP3": "the package that runs SP3 (Blender, WP-10)",
    "SP4": "the package that runs SP4 (the idle test, WP-10)",
    "SP5": "the package that runs SP5 (validators and round trips, WP-05 and WP-06)",
}


class Bad(Exception):
    pass


def read(path):
    try:
        return open(path, "r", encoding="utf-8").read()
    except (OSError, UnicodeDecodeError) as e:
        raise Bad("cannot read %s (%s)" % (os.path.basename(path), type(e).__name__))


def parse_part(text, spike):
    """-> {part name: [lines]}; a part is introduced by `<!-- part: NAME -->`."""
    out, cur = {}, None
    for ln in text.splitlines():
        m = re.match(r"^<!-- part: ([a-z-]+) -->\s*$", ln)
        if m:
            if m.group(1) not in PARTS:
                raise Bad("%s.md: unknown part %r (allowed: %s)" % (spike, m.group(1), ", ".join(PARTS)))
            cur = m.group(1)
            if cur in out:
                raise Bad("%s.md: the part %r appears twice" % (spike, cur))
            out[cur] = []
            continue
        if re.match(r"^<!--.*-->\s*$", ln):
            continue                       # the owner note and other comments
        if not ln.strip():
            continue
        if cur is None:
            raise Bad("%s.md: text before the first `<!-- part: NAME -->` line: %s" % (spike, ln[:50]))
        out[cur].append(ln.rstrip("\n"))
    return out


def check_part(spike, parts):
    n = spike[2:]
    rows = parts.get("row", [])
    if len(rows) != 1 or not re.match(r"^\| \*\*SP%s\*\* \|" % n, rows[0]):
        raise Bad("%s.md: the row part must hold exactly one table row that starts with `| **%s** |`" % (spike, spike))
    for ln in parts.get("rule", []):
        if not re.match(r"^\* SP%s, " % n, ln):
            raise Bad("%s.md: a rule bullet must start with `* %s, `: %s" % (spike, spike, ln[:50]))
    for ln in parts.get("not-said", []):
        if not ln.startswith("* "):
            raise Bad("%s.md: a not-said line must be a bullet that starts with `* `: %s" % (spike, ln[:50]))
    if "tests" in parts:
        if spike != "SP1":
            raise Bad("%s.md: test rows belong to SP1 only (the template has one test table, the SP1 table)" % spike)
        for ln in parts["tests"]:
            if not re.match(r"^\| \*\*T[1-6]\*\*", ln):
                raise Bad("SP1.md: a tests line must be a table row that starts with `| **Tn**`: %s" % ln[:50])


def load_parts(d):
    allp = {}
    for sp in SPIKES:
        p = os.path.join(d, sp + ".md")
        parts = parse_part(read(p), sp)
        check_part(sp, parts)
        allp[sp] = parts
    return allp


def build(d):
    template = read(os.path.join(d, "template.md"))
    allp = load_parts(d)
    lines = template.rstrip("\n").split("\n")
    out = []
    seen = set()
    for ln in lines:
        m = re.match(r"^<!-- insert: ([a-z-]+) -->\s*$", ln)
        if not m:
            out.append(ln)
            continue
        name = m.group(1)
        part = [k for k, v in INSERT.items() if v == name]
        if not part:
            raise Bad("template.md: unknown placeholder %r" % name)
        if name in seen:
            raise Bad("template.md: the placeholder %r appears twice" % name)
        seen.add(name)
        for sp in SPIKES:
            out.extend(allp[sp].get(part[0], []))
    missing = [v for v in INSERT.values() if v not in seen]
    if missing:
        raise Bad("template.md: placeholder(s) missing: %s" % ", ".join(missing))
    return BANNER + "\n" + "\n".join(out) + "\n"


def atomic_write(path, text):
    d = os.path.dirname(os.path.abspath(path))
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".assemble-")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def classify_not_said(ln):
    """Which spike a 'does not say' bullet belongs to, by the name it uses; None leaves it in the template."""
    if re.search(r"\bSP4\b", ln):
        return "SP4"
    if re.search(r"\bSP3\b|hero frame", ln):
        return "SP3"
    if re.search(r"\bSP1\b|T2 and T4", ln):
        return "SP1"
    if re.search(r"\bSP2\b", ln):
        return "SP2"
    if re.search(r"\bSP5\b", ln):
        return "SP5"
    return None


def do_import(verdicts, d):
    text = read(verdicts)
    lines = text.rstrip("\n").split("\n")
    if lines and lines[0].startswith("<!-- GENERATED by spikes/verdicts/assemble.py"):
        lines = lines[1:]
    parts = {sp: {} for sp in SPIKES}
    tmpl, placed = [], set()
    in_not_said = False
    for ln in lines:
        if ln.startswith("## "):
            in_not_said = ln.strip() == "## What this file does not say"
        m_row = re.match(r"^\| \*\*(SP[1-5])\*\* \|", ln)
        m_test = re.match(r"^\| \*\*T[1-6]\*\*", ln)
        m_rule = re.match(r"^\* (SP[1-5]), ", ln)
        target = None
        if m_row:
            target = (m_row.group(1), "row")
        elif m_test:
            target = ("SP1", "tests")
        elif m_rule:
            target = (m_rule.group(1), "rule")
        elif in_not_said and ln.startswith("* ") and classify_not_said(ln):
            target = (classify_not_said(ln), "not-said")
        if target is None:
            tmpl.append(ln)
            continue
        sp, part = target
        parts[sp].setdefault(part, []).append(ln)
        if INSERT[part] not in placed:
            placed.add(INSERT[part])
            tmpl.append("<!-- insert: %s -->" % INSERT[part])
    missing = [v for v in INSERT.values() if v not in placed]
    if missing:
        raise Bad("the file has no %s to move into parts (is this the verdict file?)" % ", ".join(missing))
    os.makedirs(d, exist_ok=True)
    atomic_write(os.path.join(d, "template.md"), "\n".join(tmpl) + "\n")
    for sp in SPIKES:
        body = ["<!-- owner: %s; the only writer of this file. Edit it, then run: python3 -I spikes/verdicts/assemble.py -->" % OWNER_NOTE[sp]]
        for part in PARTS:
            if part in parts[sp]:
                body.append("<!-- part: %s -->" % part)
                body.extend(parts[sp][part])
        atomic_write(os.path.join(d, sp + ".md"), "\n".join(body) + "\n")
    return {sp: {k: len(v) for k, v in parts[sp].items()} for sp in SPIKES}


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", nargs="?", default="assemble", choices=["assemble", "check", "import"])
    ap.add_argument("--verdicts", default=os.path.join(REPO, "spikes", "VERDICTS-W2.md"))
    ap.add_argument("--dir", default=HERE)
    a = ap.parse_args(argv)
    try:
        if a.cmd == "import":
            counts = do_import(a.verdicts, a.dir)
            print("assemble: split the verdict file into template.md and %d spike files: %s" % (
                len(SPIKES), "; ".join("%s %s" % (sp, ", ".join("%s %d" % kv for kv in sorted(c.items()))) for sp, c in counts.items())))
            return 0
        want = build(a.dir)
        if a.cmd == "check":
            have = read(a.verdicts)
            if have == want:
                print("assemble: %s is exactly what the parts assemble to (%d lines)" % (os.path.basename(a.verdicts), want.count("\n")))
                return 0
            diff = list(difflib.unified_diff(have.splitlines(), want.splitlines(), "VERDICTS-W2.md (now)", "assembled from the parts", lineterm="", n=0))
            print("assemble: DIFFERENT. %s is not what the parts assemble to: someone edited the generated file by hand, or a part changed without a new assemble." % os.path.basename(a.verdicts))
            for ln in diff[:12]:
                print("   " + ln[:200])
            print("   Fix: if a part is the newer text, run `python3 -I spikes/verdicts/assemble.py`; if the generated file holds a hand edit worth keeping, move it into the right part file first "
                  "(or run `python3 -I spikes/verdicts/assemble.py import` while no part has changed) and then assemble.")
            return 1
        atomic_write(a.verdicts, want)
        print("assemble: wrote %s (%d lines) from template.md and %d spike files" % (os.path.basename(a.verdicts), want.count("\n"), len(SPIKES)))
        return 0
    except Bad as e:
        print("assemble: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
